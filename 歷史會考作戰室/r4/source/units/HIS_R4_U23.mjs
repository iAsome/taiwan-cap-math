function visibleLength(value) {
  return Array.from(String(value).replace(/\s/gu, "")).length;
}

function hanLength(value) {
  return (String(value).match(/\p{Script=Han}/gu) ?? []).length;
}

function assertSource(source) {
  const expectedSkills = [155, 156, 157, 158, 159, 160, 161].map((number) => `HIS_R4_S${number}`);
  if (source.lectures.length !== 7 || source.questions.length !== 84 || source.stimuli.length !== 7 || source.stimulusQuestions.length !== 21) throw new Error(`${source.unitId}: inventory mismatch`);
  if (source.lectures.map((value) => value.skillId).join("|") !== expectedSkills.join("|")) throw new Error(`${source.unitId}: frozen skill order mismatch`);
  for (const lecture of source.lectures) {
    if (lecture.sections.length < 4 || lecture.workedExamples.length < 3 || lecture.misconceptions.length < 4 || lecture.checks.length < 3) throw new Error(`${lecture.id}: lecture floor mismatch`);
    for (const section of lecture.sections) if (hanLength(section.content) < 35) throw new Error(`${section.id}: section too short`);
    for (const worked of lecture.workedExamples) if (hanLength(worked.why) < 25) throw new Error(`${worked.id}: why too short`);
  }
  const visibleKeys = new Set();
  const essenceKeys = new Set();
  for (const question of [...source.questions, ...source.stimulusQuestions]) {
    if (question.options.length !== 4 || new Set(question.options).size !== 4 || question.reasons.length !== 4 || question.reviews.length !== 2) throw new Error(`${question.id}: question structure mismatch`);
    if (!Number.isInteger(question.answerIndex) || question.answerIndex < 0 || question.answerIndex > 3) throw new Error(`${question.id}: invalid answerIndex`);
    for (const reason of question.reasons) if (visibleLength(reason) < 8) throw new Error(`${question.id}: option reason too short`);
    const visibleKey = JSON.stringify([question.stem, [...question.options].sort()]);
    const normalize = (value) => String(value).normalize("NFKC").toLowerCase().replace(/[\p{P}\p{S}\s\d]+/gu, "");
    const essenceKey = JSON.stringify([normalize(question.stem), [...question.options].map(normalize).sort()]);
    if (visibleKeys.has(visibleKey) || essenceKeys.has(essenceKey)) throw new Error(`${question.id}: duplicate question`);
    visibleKeys.add(visibleKey);
    essenceKeys.add(essenceKey);
  }
  for (const skillId of expectedSkills) {
    const bank = source.questions.filter((value) => value.skillId === skillId);
    const answers = [0, 1, 2, 3].map((answerIndex) => bank.filter((value) => value.answerIndex === answerIndex).length);
    const levels = ["foundation", "standard", "advanced", "transfer"].map((level) => bank.filter((value) => value.difficulty === level).length);
    if (answers.some((count) => count !== 3)) throw new Error(`${skillId}: answerIndex distribution must be 3/3/3/3`);
    if (levels.join("/") !== "3/4/3/2") throw new Error(`${skillId}: difficulty distribution mismatch`);
  }
  const stimulusAnswers = [0, 1, 2, 3].map((answerIndex) => source.stimulusQuestions.filter((value) => value.answerIndex === answerIndex).length);
  if (stimulusAnswers.join("/") !== "6/5/5/5") throw new Error(`${source.unitId}: stimulus answerIndex distribution must be 6/5/5/5`);
  const stimulusIds = new Set(source.stimuli.map((value) => value.id));
  for (const value of source.stimulusQuestions) if (!stimulusIds.has(value.stimulusId)) throw new Error(`${value.id}: missing stimulus link`);
  for (const value of source.stimuli) {
    if (!value.content.label || !value.content.sourceNote || !value.content.blocks.length || !value.accessibility.plainText || !value.accessibility.longDescription) throw new Error(`${value.id}: incomplete stimulus`);
  }
}

const source = { unitId: "HIS_R4_U23", lectures, questions, stimuli, stimulusQuestions };
assertSource(source);

