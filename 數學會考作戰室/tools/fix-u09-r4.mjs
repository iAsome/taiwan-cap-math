function countZh(t) {
  return (t.match(/[\u4e00-\u9fff]/g) || []).length;
}

function stripAll(text) {
  let s = text;
  for (const p of STRIP_PHRASES) while (s.includes(p)) s = s.replace(p, "");
  return s.replace(/\s{2,}/g, " ").replace(/。+/g, "。").trim();
}

function dedupe(e) {
  const parts = e.split("。").filter(Boolean);
  const seen = new Set();
  const out = [];
  for (const p of parts) {
    const k = p.trim();
    if (k && !seen.has(k)) {
      seen.add(k);
      out.push(k);
    }
  }
  return out.length ? out.join("。") + "。" : e;
}

function tailOk(q, tail) {
  const plain = q.text.replace(/\s+/g, "");
  for (let len = 9; len <= Math.min(plain.length, 24); len++) {
    for (let i = 0; i <= plain.length - len; i++) {
      const sub = plain.slice(i, i + len);
      if (/^[\u4e00-\u9fff？?，,、：:]+$/.test(sub) && tail.includes(sub)) return false;
    }
  }
  return true;
}

function padMin45(q, e) {
  let out = e.endsWith("。") ? e : e + "。";
  let guard = 0;
  const wrongs = q.choices.filter((_, i) => i !== q.answerIndex);
  const pads = [
    w => `錯選${w}與題幹所列數字或所求量對不上。`,
    w => `${w}是把部分資料誤當成最終答案。`,
    w => `若得${w}，多半是漏加、多算或統計量用錯。`
  ];
  while (countZh(out) < 45 && guard++ < 12) {
    const w = wrongs[(guard - 1) % wrongs.length];
    const add = pads[(guard - 1) % pads.length](w);
    if (!tailOk(q, add) || out.includes(add)) continue;
    out += add;
  }
  return out;
}

function fixNumericPrefix(e) {
  const t = e.trim();
  if (/^(0[1-9]|1[0-2])[\u4e00-\u9fff{]/.test(t)) return `依題意，${t}`;
  return e;
}

function fixExplanation(q) {
  const e = FULL[q.questionId] ? FULL[q.questionId] : dedupe(stripAll(q.explanation));
  return fixNumericPrefix(padMin45(q, e));
}

function writePart(file, partName, items, lectures) {
  fs.writeFileSync(
    file,
    `export const ${partName} = ${JSON.stringify(items, null, 2)};\n\nexport const ${partName.replace("PART", "LECTURES")} = ${JSON.stringify(lectures, null, 2)};\n`,
    "utf8"
  );
}

