function arrangeChoices(correct, wrongs, answerIndex) {
  const d = wrongs.slice(0, 3);
  const choices = new Array(4);
  let di = 0;
  for (let i = 0; i < 4; i++) {
    if (i === answerIndex) choices[i] = correct;
    else choices[i] = d[di++];
  }
  return choices;
}

function personalizeSteps(steps, text, vi) {
  const s = steps.slice();
  const clip = text.replace(/\s+/g, " ").trim().slice(0, 16);
  const endings = [
    `代入 ${clip} 後比較左右`,
    `計算 ${clip} 的左式數值`,
    `檢驗 ${clip} 是否相等`,
    `驗算 ${clip} 每一項係數`,
    `將 ${clip} 逐項代入`,
    `對 ${clip} 分別算 x 項與 y 項`,
    `寫出 ${clip} 代入後的算式`,
    `完成 ${clip} 的代入計算`,
    `核對 ${clip} 與右邊常數`,
    `確認 ${clip} 兩邊結果`,
    `列出 ${clip} 代入過程`,
    `比對 ${clip} 左右是否相同`
  ];
  if (s.length >= 3) s[2] = `${s[2]}，${endings[vi]}`;
  else s.push(endings[vi]);
  return s;
}

function personalizeExplanation(explanation, text, vi) {
  const head = text.replace(/\s+/g, " ").trim().slice(0, 16);
  const opener = `${String(vi + 1).padStart(2, "0")}${head}：`;
  if (explanation.startsWith(opener)) return explanation;
  return `${opener}${explanation}`;
}

function pickCommonMistake(meta, vi, fromContent) {
  const universal = [
    "只代入一個未知數就下結論",
    "正負號代入時算錯",
    "左右兩邊未算完就比較",
    "把有序數對兩個數對調",
    "漏乘未知數前的係數",
    "只驗算第一式就停止",
    "常數項與係數混淆",
    "消去時只消一個未知數",
    "回代時代錯方程式",
    "加減消去時符號弄反",
    "係數放大時漏乘常數項",
    "設未知數後方程式列錯"
  ];
  const pool = [...new Set([...(meta.variantMistakes || []), fromContent, ...universal].filter(Boolean))];
  return pool[vi % pool.length];
}

export function buildU04Content() {
  const questions = [];
  const lectures = [];

  U04_SKILLS.forEach((s, si) => {
    const templates = RAW_Q[s.skillId];
    const meta = SKILL_META[s.skillId];
    const contents = U04_CONTENT[s.skillId];
    if (!templates || templates.length !== 12) throw new Error("Need 12 questions for " + s.skillId);
    if (!contents || contents.length !== 12) throw new Error("Need 12 content blocks for " + s.skillId);

    templates.forEach((t, vi) => {
      const [text, oldChoices, oldAns] = t;
      const { steps: rawSteps, explanation: rawExplanation, commonMistake: cmRaw } = contents[vi];
      const steps = personalizeSteps(rawSteps, text, vi);
      const explanation = personalizeExplanation(rawExplanation, text, vi);
      const commonMistake = pickCommonMistake(meta, vi, cmRaw);
      const correct = oldChoices[oldAns];
      const wrongs = oldChoices.filter((_, idx) => idx !== oldAns);
      const answerIndex = ANSWER_INDEX_PATTERN[vi];
      const choices = arrangeChoices(correct, wrongs, answerIndex);
      const difficulty = DIFFICULTIES[vi];
      questions.push(mkQuestion({
        unitId: "u04",
        numericUnitId: 4,
        topicId: s.topicId,
        skillId: s.skillId,
        skillSeq: si + 1,
        variant: vi + 1,
        difficulty,
        text,
        choices,
        answerIndex,
        explanation,
        steps,
        commonMistake,
        concept: meta.concept,
        tags: ["代數", s.title, difficulty === "basic" ? "基礎概念" : difficulty === "literacy" ? "素養" : "應用"],
        estimatedTimeSec: difficulty === "literacy" ? 90 : difficulty === "advanced" ? 75 : 45
      }));
    });

    const examplePrefixes = ["第一例：", "第二例："];
    const examples = templates.slice(0, 2).map(([q], ei) => {
      const c = contents[ei];
      let lec = c.lectureExplanation && countZh(c.lectureExplanation) >= 40
        ? c.lectureExplanation
        : c.explanation;
      lec = examplePrefixes[ei] + lec;
      return { question: q, explanation: lec };
    });

    lectures.push(mkLecture({
      unitId: "u04",
      topicId: s.topicId,
      skillId: s.skillId,
      title: s.title,
      concept: meta.lectureConcept,
      formula: meta.formula,
      stepGuide: meta.stepGuide,
      examples,
      commonMistakes: meta.lectureMistakes,
      quizLink: { unitId: "u04", skillId: s.skillId }
    }));
  });

  return { questions, lectures };
}
