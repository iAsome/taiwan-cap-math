const PAD_FRAGMENT = /次數表|長條圖|折線圖|依題幹|加權平均須|眾數看出現|平均數相關|表格題要把|圓形圖占比|計算完成後比對/;

function stripR6(e) {
  let s = e;
  for (const re of R6_STRIP) s = s.replace(re, "");
  return s.replace(/。+/g, "。").replace(/^。+/, "").trim();
}

function dedupe(e) {
  const parts = e.split("。").filter(Boolean);
  const seen = new Set();
  const out = [];
  for (const p of parts) {
    const k = p.trim().replace(/\s+/g, "");
    if (k && !seen.has(k) && !PAD_FRAGMENT.test(p)) {
      seen.add(k);
      out.push(p.trim());
    }
  }
  return out.length ? `${out.join("。")}。` : e;
}

function finalize(q) {
  const raw = STAT_R6[q.questionId] || OVERRIDES[q.questionId] || R5_FULL[q.questionId] || q.explanation;
  let e = dedupe(stripR6(raw));
  return e.endsWith("。") ? e : `${e}。`;
}

