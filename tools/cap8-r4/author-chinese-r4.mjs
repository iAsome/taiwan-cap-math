function rotate(values, answerIndex) {
  const out = Array(values.length);
  out[answerIndex] = values[0];
  let cursor = 1;
  for (let index = 0; index < out.length; index++) if (index !== answerIndex) out[index] = values[cursor++];
  return out;
}

